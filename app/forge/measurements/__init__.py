"""Bloc III.2 — Measurement & Feature Engine (Book III).

Deterministic, offline measurement layer: immutable, versioned
measurement records with complete provenance, plus the range,
calibration, coordinate, anchor, clock/state-age, path, event and
higher-order engines that produce them.

The law of this package:

    Observed data -> Deterministic measurement -> Versioned model
    interpretation -> Governed operator eligibility.

Everything here is a **measurement** — a deterministic transformation
of observations with an explicit formula, unit, input frame and
clock/session definition.  A measurement is not a model output, not a
claim, not evidence, not a setup and never a prediction.

The package imports nothing from the Book I authority modules
(``qa/``, ``retrieval/``, ``app/forge/provenance.py``,
``app/forge/canonical.py``, ``app/forge/policy.py``) and reads the
canonical corpus read-only by id.  It opens no socket, reads no
wall clock and writes no corpus file.
"""

