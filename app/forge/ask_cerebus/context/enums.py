"""Closed vocabularies for the IV.3 context packager."""

from __future__ import annotations

from enum import Enum


class ContextOutcome(str, Enum):
    RESOLVED = "RESOLVED"
    PARTIAL = "PARTIAL"
    REFUSED = "REFUSED"


class ContextSectionId(str, Enum):
    QUERY_CONTRACT = "QUERY_CONTRACT"
    CURRENT_INTELLIGENCE = "CURRENT_INTELLIGENCE"
    CANONICAL_MODEL = "CANONICAL_MODEL"
    SETUP = "SETUP"
    CLAIMS = "CLAIMS"
    EVIDENCE = "EVIDENCE"
    LINEAGE_TERMS = "LINEAGE_TERMS"
    LIMITATIONS_NEGATIVE = "LIMITATIONS_NEGATIVE"
    GENERAL_KNOWLEDGE = "GENERAL_KNOWLEDGE"


class EpistemicLabel(str, Enum):
    CANONICAL = "CANONICAL"
    VALIDATED = "VALIDATED"
    FORWARD_OOS = "FORWARD_OOS"
    CANDIDATE = "CANDIDATE"
    RESEARCH_FLAG = "RESEARCH_FLAG"
    HISTORICAL = "HISTORICAL"
    NEGATIVE_EVIDENCE = "NEGATIVE_EVIDENCE"
    PARKED = "PARKED"
    SUPERSEDED = "SUPERSEDED"
    INFERENCE = "INFERENCE"
    GENERAL_KNOWLEDGE = "GENERAL_KNOWLEDGE"
    INSUFFICIENT_EVIDENCE = "INSUFFICIENT_EVIDENCE"


class TrustClass(str, Enum):
    TRUSTED_CONTROL = "TRUSTED_CONTROL"
    UNTRUSTED_DATA = "UNTRUSTED_DATA"


class SmallNFlag(str, Enum):
    TRUE = "TRUE"
    FALSE = "FALSE"
    UNRESOLVED = "UNRESOLVED"


class ContextIssueCode(str, Enum):
    MISSING_EVIDENCE = "MISSING_EVIDENCE"
    CONTEXT_BUDGET_TRIMMED = "CONTEXT_BUDGET_TRIMMED"
    EPISTEMIC_LABEL_UNRESOLVED = "EPISTEMIC_LABEL_UNRESOLVED"
    DETAIL_NOT_SUPPLIED = "DETAIL_NOT_SUPPLIED"
    N_NOT_PROVIDED = "N_NOT_PROVIDED"
    SMALL_N_UNRESOLVED = "SMALL_N_UNRESOLVED"
    EXPOSURE_EXCLUDED = "EXPOSURE_EXCLUDED"
    UPSTREAM_LIMITATION = "UPSTREAM_LIMITATION"
    UPSTREAM_REFUSAL = "UPSTREAM_REFUSAL"
    DUPLICATE_SUPPRESSED = "DUPLICATE_SUPPRESSED"
    INAPPLICABLE_SECTION = "INAPPLICABLE_SECTION"


class ContextRefusalCode(str, Enum):
    CONTEXT_CONTRACT_UNSUPPORTED = "CONTEXT_CONTRACT_UNSUPPORTED"
    CONTEXT_INPUT_MALFORMED = "CONTEXT_INPUT_MALFORMED"
    CONTEXT_BUDGET_EXCEEDED = "CONTEXT_BUDGET_EXCEEDED"
    CONTEXT_EXPOSURE_VIOLATION = "CONTEXT_EXPOSURE_VIOLATION"
    CONTEXT_INTEGRITY_FAILURE = "CONTEXT_INTEGRITY_FAILURE"
    CONTEXT_DETAIL_UNAUTHORIZED = "CONTEXT_DETAIL_UNAUTHORIZED"


SECTION_ORDER = (
    ContextSectionId.QUERY_CONTRACT,
    ContextSectionId.CURRENT_INTELLIGENCE,
    ContextSectionId.CANONICAL_MODEL,
    ContextSectionId.SETUP,
    ContextSectionId.CLAIMS,
    ContextSectionId.EVIDENCE,
    ContextSectionId.LINEAGE_TERMS,
    ContextSectionId.LIMITATIONS_NEGATIVE,
    ContextSectionId.GENERAL_KNOWLEDGE,
)

SECTION_RANK = {section: index for index, section in enumerate(SECTION_ORDER)}

