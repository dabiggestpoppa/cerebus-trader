"""Closed vocabularies for IV.2 retrieval.

Nothing here grants authority. Tiers describe precedence, limitations describe
what could not be established, and refusals describe why retrieval stopped.
"""

from __future__ import annotations

from enum import Enum, IntEnum


class RetrievalOutcome(str, Enum):
    RESOLVED = "RESOLVED"
    PARTIAL = "PARTIAL"
    UNAVAILABLE = "UNAVAILABLE"
    REFUSED = "REFUSED"


class PrecedenceTier(IntEnum):
    DIRECT_CANONICAL = 1
    LINKED_CLAIM_EVIDENCE = 2
    CURRENT_INTELLIGENCE = 3
    LINEAGE_DOCTRINE = 4
    SOURCE_DERIVED_PASSAGE = 5
    GENERAL_KNOWLEDGE = 6


class EvidenceJoinStatus(str, Enum):
    VERIFIED = "VERIFIED"
    SUPPORTED = "SUPPORTED"
    UNSUPPORTED = "UNSUPPORTED"
    MISSING = "MISSING"
    CONFLICT = "CONFLICT"
    INCOMPARABLE = "INCOMPARABLE"


class LimitationCode(str, Enum):
    UNRESOLVED_IDENTITY = "UNRESOLVED_IDENTITY"
    UNSUPPORTED_IDENTITY = "UNSUPPORTED_IDENTITY"
    UNAVAILABLE_GENERATION = "UNAVAILABLE_GENERATION"
    UNSUPPORTED_STATISTIC = "UNSUPPORTED_STATISTIC"
    MATERIAL_AMBIGUITY = "MATERIAL_AMBIGUITY"
    DEPTH_CAPPED = "DEPTH_CAPPED"
    HISTORICAL_GENERATION = "HISTORICAL_GENERATION"
    HISTORICAL_UNAVAILABLE = "HISTORICAL_UNAVAILABLE"
    PROVIDER_NOT_CONFIGURED = "PROVIDER_NOT_CONFIGURED"
    REQUIRED_FIELDS_UNRESOLVED = "REQUIRED_FIELDS_UNRESOLVED"
    NO_GO_ACTIVE = "NO_GO_ACTIVE"
    SETUP_BLOCKED = "SETUP_BLOCKED"
    SETUP_NOT_ELIGIBLE = "SETUP_NOT_ELIGIBLE"
    RESEARCH_ONLY_NOT_PRODUCTION = "RESEARCH_ONLY_NOT_PRODUCTION"
    AUTOMATION_NOT_APPROVED = "AUTOMATION_NOT_APPROVED"
    EVIDENCE_INSUFFICIENT = "EVIDENCE_INSUFFICIENT"
    EVIDENCE_CONFLICT = "EVIDENCE_CONFLICT"
    INCOMPARABLE_EVIDENCE = "INCOMPARABLE_EVIDENCE"
    SOURCE_DISAGREEMENT = "SOURCE_DISAGREEMENT"
    NEGATIVE_EVIDENCE = "NEGATIVE_EVIDENCE"
    LIMITED_QUOTE_SCOPE = "LIMITED_QUOTE_SCOPE"
    POLICY_DENIED = "POLICY_DENIED"
    RETRIEVAL_UNAVAILABLE = "RETRIEVAL_UNAVAILABLE"


class RefusalCode(str, Enum):
    EXPOSURE_FORBIDDEN = "EXPOSURE_FORBIDDEN"
    HISTORICAL_UNAVAILABLE = "HISTORICAL_UNAVAILABLE"
    PROVIDER_NOT_CONFIGURED = "PROVIDER_NOT_CONFIGURED"
    REQUIRED_FIELDS_UNRESOLVED = "REQUIRED_FIELDS_UNRESOLVED"
    UNSUPPORTED_PLAN_CONTRACT = "UNSUPPORTED_PLAN_CONTRACT"
    MALFORMED_REQUEST = "MALFORMED_REQUEST"
    RETRIEVAL_UNAVAILABLE = "RETRIEVAL_UNAVAILABLE"
    RESEARCH_ONLY_NOT_PRODUCTION = "RESEARCH_ONLY_NOT_PRODUCTION"
    AUTOMATION_NOT_APPROVED = "AUTOMATION_NOT_APPROVED"
    SETUP_BLOCKED = "SETUP_BLOCKED"
    SETUP_NOT_ELIGIBLE = "SETUP_NOT_ELIGIBLE"


class RejectionClass(str, Enum):
    NOT_FOUND = "NOT_FOUND"
    POLICY_DENIED = "POLICY_DENIED"
    VERSION_MISMATCH = "VERSION_MISMATCH"
    STATUS_INELIGIBLE = "STATUS_INELIGIBLE"
    DUPLICATE = "DUPLICATE"
    SEMANTIC_UNAUTHORIZED = "SEMANTIC_UNAUTHORIZED"
    LIMIT = "LIMIT"


class TraceClass(str, Enum):
    INTERNAL = "INTERNAL"
    CONSUMER = "CONSUMER"
    REFUSAL = "REFUSAL"


