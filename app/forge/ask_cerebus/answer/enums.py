"""Closed vocabularies for Book IV / Bloc IV.5."""

from __future__ import annotations

from enum import Enum


class AnswerOutcome(str, Enum):
    VALIDATED_ANSWER = "VALIDATED_ANSWER"
    GOVERNED_REFUSAL = "GOVERNED_REFUSAL"


class AnswerDepth(str, Enum):
    BEGINNER = "BEGINNER"
    OPERATOR = "OPERATOR"
    RESEARCHER = "RESEARCHER"


class AnswerRefusalCode(str, Enum):
    """The six frozen answer-level refusal codes (R62)."""

    INSUFFICIENT_EVIDENCE = "INSUFFICIENT_EVIDENCE"
    CURRENT_DATA_UNAVAILABLE = "CURRENT_DATA_UNAVAILABLE"
    MODEL_VERSION_UNAVAILABLE = "MODEL_VERSION_UNAVAILABLE"
    SETUP_NOT_ENCODED = "SETUP_NOT_ENCODED"
    ACCESS_NOT_ENTITLED = "ACCESS_NOT_ENTITLED"
    AMBIGUOUS_SCOPE = "AMBIGUOUS_SCOPE"


#: Frozen precedence, highest first (R63). F3-open ratification.
REFUSAL_PRECEDENCE = (
    AnswerRefusalCode.ACCESS_NOT_ENTITLED,
    AnswerRefusalCode.AMBIGUOUS_SCOPE,
    AnswerRefusalCode.MODEL_VERSION_UNAVAILABLE,
    AnswerRefusalCode.CURRENT_DATA_UNAVAILABLE,
    AnswerRefusalCode.SETUP_NOT_ENCODED,
    AnswerRefusalCode.INSUFFICIENT_EVIDENCE,
)

REFUSAL_RANK = {code: index for index, code in enumerate(REFUSAL_PRECEDENCE)}


