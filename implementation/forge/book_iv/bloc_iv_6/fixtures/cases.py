def _case(
    number: int,
    family: CaseFamily,
    kind: CaseKind,
    query: str,
    *,
    mode: ExecutionMode = ExecutionMode.SEALED,
    fixture: str = "operator",
    variant: str = "as_is",
    depth: str = "OPERATOR",
    intent: str = "SETUP_CONTEXT",
    entities: tuple[str, ...] = (),
    market: str = "XAUUSD",
    models: tuple[str, ...] = (),
    scope: TimeScope = TimeScope.ANY,
    authority: Authority = Authority.FIXTURE_FACT,
    outcome: ExpectedOutcomeKind = ANSWER,
    code: str | None = None,
    finding: FindingCode | None = None,
    required: tuple[str, ...] = (),
    forbidden: tuple[str, ...] = (),
    numbers: tuple[str, ...] = (),
    limitations: tuple[str, ...] = (),
    citations: tuple[str, ...] = (),
    eligibility: str | None = None,
    freshness: ExpectedFreshness = ExpectedFreshness.NOT_REQUIRED,
    validation: tuple[str, ...] = (),
    fields: tuple[str, ...] = (),
    population: tuple[MetricId, ...] = (),
    owner: enums.AttributionOwner | None = None,
    notes: str = "",
    marker: str = "",
) -> EvaluationCase:
    if mode is ExecutionMode.CHAIN:
        fixture_source = f"CHAIN:{query}"
        builder, record, path = "build_chain_index", query, CHAIN_FILE
    else:
        fixture_source = fixture
        builder, record, path = fixture, f"EV-{number:03d}", FIXTURE_FILE
    return EvaluationCase(
        case_id=f"EV-{number:03d}",
        family=family,
        kind=kind,
        execution_mode=mode,
        query_text=query,
        depth=depth,
        intent_expected=intent,
        entities_expected=entities,
        market=market,
        model_ids=models,
        time_scope=scope,
        fixture_source=fixture_source,
        evidence_path=ExpectedEvidencePath(
            fixture_path=path,
            builder=builder,
            record=record,
            values=(("case", f"EV-{number:03d}"), ("query", query)),
        ),
        authority=authority,
        expected_outcome=outcome,
        expected_refusal_code=code,
        expected_finding_class=finding,
        required_claims=tuple(ExpectedClaim(token) for token in required),
        forbidden_claims=tuple(ExpectedClaim(token) for token in forbidden),
        forbidden_numbers=numbers,
        required_limitations=limitations,
        expected_citations=citations,
        expected_eligibility=eligibility,
        expected_freshness=freshness,
        expected_validation_codes=validation,
        required_fields=fields,
        score_population=population,
        unresolved_owner=owner,
        notes=notes,
        draft_variant=variant,
        payload_marker=marker,
    )


