"""The 120 golden cases of Bloc IV.6.

Expectations are literals. They come from four authorities only (R6):

``FIXTURE_FACT``      a value read from a ratified fixture record
``FROZEN_RULE``       the six refusals, four eligibility values or layer labels
``OPERATOR_ASSERTION`` a written CEREBUS-doctrine assertion with a named owner
``SYNTHETIC_INPUT``   the case itself defines the only possible truth

No expectation below is derived by running the system under test. Where a
refusal code follows from a validation finding, the frozen decay table in IV.5
(``answer.enums.FINDING_REFUSAL``) is the FROZEN_RULE authority; the case names
the finer finding class AND the code it decays to.
"""

