"""Materialise the frozen IV.6 dataset from the authored case table.

Run from the repository root::

    python implementation/forge/book_iv/bloc_iv_6/fixtures/generate.py

The generator writes ``EV-001.json`` … ``EV-120.json``, ``DATASET_MANIFEST.json``
and ``PROVENANCE.md``. It never runs the corpus: expectations come from the
authored literals in ``cases.py``, never from an execution (PLAN.md §12, rule 2).
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[4]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from app.forge.ask_cerebus.evaluation import dataset, versions  # noqa: E402
from app.forge.ask_cerebus.evaluation.schema import EvaluationDataset, dataset_from_cases  # noqa: E402


def _load_cases_module():
    spec = importlib.util.spec_from_file_location("iv6_case_table", HERE / "cases.py")
    if spec is None or spec.loader is None:  # pragma: no cover - import machinery
        raise RuntimeError("cannot load the IV.6 case table")
    module = importlib.util.module_from_spec(spec)
    sys.modules["iv6_case_table"] = module
    spec.loader.exec_module(module)
    return module


def build() -> EvaluationDataset:
    module = _load_cases_module()
    cases = tuple(module.cases())
    built = dataset_from_cases(
        cases,
        dataset_version=versions.EVALUATION_DATASET_V1,
        schema_version=versions.CASE_SCHEMA_V1,
    )
    problems = dataset.validate_dataset(built)
    if problems:
        raise SystemExit("invalid dataset:\n- " + "\n- ".join(problems))
    return built


def provenance(dataset: EvaluationDataset) -> str:
    bands = "\n".join(f"| {name} | {count} |" for name, count in dataset.band_counts)
    balance = "\n".join(f"| {name} | {count} |" for name, count in dataset.balance_report)
    pins = "\n".join(f"| `{path}` | `{blob}` |" for path, blob in sorted(versions.UPSTREAM_PINS.items()))
    return f"""# IV.6 fixture provenance

Generated by `implementation/forge/book_iv/bloc_iv_6/fixtures/generate.py` from the
authored case table in `cases.py`. Nothing in this directory is produced by a run
of the system under test: every expectation is a literal in the authored table.

- dataset version: `{dataset.dataset_version}`
- case schema version: `{dataset.schema_version}`
- case count: {len(dataset.cases)}
- dataset digest: `{dataset.digest}`

## Bands

| band | cases |
| --- | --- |
{bands}

## Populations

| population | cases |
| --- | --- |
{balance}

## Upstream pins

Each pin is the git blob id of the frozen file; `regression.verify_upstream_pins`
reproduces it with `git hash-object` semantics.

| file | blob |
| --- | --- |
{pins}

## Reused fixtures

`_builders.py` loads the ratified IV.5 builders (`bloc_iv_5/fixtures/_builders.py`)
and the IV.2 retrieval builders by path. IV.6 owns only this directory's case
table, draft variants and three custom packages (`p90_phi`, `btc_pair`,
`layer_mix`); it does not fork any earlier fixture.
"""


def main() -> int:
    built = build()
    written = dataset.write_dataset(built, HERE)
    (HERE / "PROVENANCE.md").write_text(provenance(built), encoding="utf-8")
    print(f"wrote {len(written)} files for {len(built.cases)} cases")
    print(f"dataset digest: {built.digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
